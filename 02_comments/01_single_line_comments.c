// Topic: Single-line comments.
//
// A comment is a note for people reading the code. The compiler ignores it, so
// it never affects what the program does. A single-line comment starts with two
// slashes and runs to the end of that line. It can sit on its own line or come
// after code on the same line.
//
// Output:
//   First Name: Arthur
//   Last Name: Morgan
#include <stdio.h>
int main()
{
    // this program prints first name and last name
    // this is a comment
    printf("First Name: Arthur\n");
    printf("Last Name: Morgan\n");

    return 0;
}
